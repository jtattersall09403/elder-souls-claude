#!/usr/bin/env node
// w1-21-r3-sample-table.mjs — PUBLISH THE PER-SCREEN, PER-CHECK SAMPLE TABLE.
//
// W1-21 round 3, brief item 1: "Fix every one of the fifteen so it carries its sample count, and
// make the grader refuse to grade a check that measured nothing. **Publish the per-screen,
// per-check sample table.**"
//
// This reads the artifacts the detectors wrote — it measures nothing itself — and assembles one
// table. A detector whose artifact is absent is reported as ABSENT rather than skipped, because
// the whole subject of this round is checks that report nothing and look clean doing it.
import fs from 'node:fs';
import path from 'node:path';
import { parseArgs, wantsHelp, usage, log, RUNS_DIR, REPO_ROOT, ensureDir } from '../lib/cli.mjs';

const USAGE = `
w1-21-r3-sample-table.mjs — assemble the published sample table from the detectors' artifacts.

USAGE
  node tools/ui/w1-21-r3-sample-table.mjs [--out <dir>]

EXIT 0 = every detector's artifact was found and every check carries a sample count
       1 = a detector's artifact is missing, or a check in one carries no sample count
`;

const args = parseArgs();
if (wantsHelp(args)) usage(USAGE);
const RUN = path.join(RUNS_DIR, String(args.out || 'W1-21-R3'));
ensureDir(RUN);

const SOURCES = [
  ['ui-metrics.mjs', 'RI-UIX06', path.join(RUNS_DIR, 'W1-21-R3-UI-METRICS', 'ui-metrics.json')],
  ['ui-forbidden.mjs', 'RI-UIX01', path.join(RUNS_DIR, 'W1-21-R3-UI-FORBIDDEN', 'ui-forbidden.json')],
  ['ui-layer.mjs', 'RI-UIX02', path.join(RUNS_DIR, 'W1-21-R3-UI-LAYER', 'ui-layer.json')],
  ['marker-diff.mjs', 'RI-UIX02', path.join(RUNS_DIR, 'W1-21-R3-MARKER-DIFF', 'marker-diff.json')],
  ['marker-scan.mjs', 'RI-UIX02', path.join(RUNS_DIR, 'W1-21-R3-MARKER-SCAN', 'marker-scan.json')],
  ['ui-census.mjs', 'RI-UIX01', path.join(RUNS_DIR, 'W1-21-R3-UI-CENSUS', 'ui-census.json')],
];

const rows = [];
const missing = [];
const noSamples = [];
let metrics = null;
for (const [tool, item, file] of SOURCES) {
  if (!fs.existsSync(file)) { missing.push([tool, file]); continue; }
  const j = JSON.parse(fs.readFileSync(file, 'utf8'));
  if (tool === 'ui-metrics.mjs') metrics = j;
  for (const c of j.checks || []) {
    if (typeof c.samples !== 'number') noSamples.push(`${tool}:${c.id}`);
    rows.push({ tool, item, ...c });
  }
}

const esc = (s) => String(s === null || s === undefined ? '' : s).replace(/\|/g, '\\|');
const md = [];
md.push('# W1-21 round 3 — the per-check sample table');
md.push('');
md.push('Generated by `tools/ui/w1-21-r3-sample-table.mjs` from the detectors\' own artifacts.');
md.push('');
md.push('**Every graded check in this piece now carries the number of things it looked at, and a');
md.push('check whose sample set is empty reports `EMPTY` and cannot report `PASS`** — see');
md.push('`tools/lib/graded.mjs`, and `tools/ui/w1-21-r3-empty.mjs` for the run that takes each');
md.push('check\'s subject away and confirms none of them goes green.');
md.push('');
md.push('| Tool | Item | Check | Status | Samples | One sample is | Detail |');
md.push('|---|---|---|---|---|---|---|');
for (const r of rows) {
  const n = `${r.samples}${typeof r.expected === 'number' ? ` of ${r.expected}` : ''}`;
  md.push(`| \`${r.tool}\` | ${r.item} | ${r.id} | **${r.status}** | ${n} | ${esc(r.sample_of)} | ${esc(r.detail).slice(0, 220)} |`);
}

// The PER-SCREEN half, which only ui-metrics can give: what each screen contributed.
if (metrics && metrics.captures && metrics.captures.length) {
  md.push('');
  md.push('## Per screen, per capture configuration (`ui-metrics.mjs`)');
  md.push('');
  md.push('`stem` is FD1/FD2\'s sample, `elements` is FD4\'s, `edge px` is FD6\'s, `bits` is FD7\'s.');
  md.push('');
  md.push('| Screen | Config | Stem crossings | Visible elements | Graded edge px | Gradient bits | Worst edge ΔE2000 |');
  md.push('|---|---|---|---|---|---|---|');
  for (const c of metrics.captures) {
    md.push(`| ${c.screen} | ${c.css.join('×')}@${c.dpr} | ${c.stem_samples} | ${c.elements_visible} | ${c.edge_fringe_samples} | ${c.gradient_bits} | ${c.edge_fringe_de2000} |`);
  }
  if (metrics.fd6) {
    md.push('');
    md.push('## FD6, in the unit `RI-UIX06` specifies');
    md.push('');
    md.push('| | |');
    md.push('|---|---|');
    for (const [k, v] of Object.entries(metrics.fd6)) md.push(`| ${k} | ${esc(JSON.stringify(v))} |`);
  }
}

if (missing.length) {
  md.push('');
  md.push('## Detectors whose artifact is ABSENT');
  md.push('');
  md.push('Not run this round, or run and not written. Recorded rather than omitted.');
  md.push('');
  for (const [tool, file] of missing) md.push(`- \`${tool}\` — expected \`${path.relative(REPO_ROOT, file)}\``);
}

const outFile = path.join(RUN, 'sample-table.md');
fs.writeFileSync(outFile, md.join('\n') + '\n');
log(`sample table: ${rows.length} graded checks from ${SOURCES.length - missing.length} of ${SOURCES.length} detectors -> ${path.relative(REPO_ROOT, outFile)}`);
if (missing.length) log(`  ABSENT: ${missing.map((m) => m[0]).join(', ')}`);
if (noSamples.length) log(`  CHECKS WITH NO SAMPLE COUNT: ${noSamples.join(', ')}`);
process.exit(missing.length || noSamples.length ? 1 : 0);
