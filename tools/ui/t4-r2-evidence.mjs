#!/usr/bin/env node
// t4-r2-evidence.mjs — writes `corpus/90-verdicts/wave1/artifacts/T4-r2/EVIDENCE.md` from the
// measurement JSONs, so every number in that document is read off a file at the moment it is
// written rather than remembered (CLAUDE.md rule 0b).
//
// It refuses to write a comparison it does not have both sides of, and says which side is missing
// instead of quietly printing one arm. A table with a blank control column is a table that invites
// the reader to supply the control from memory.
import fs from 'node:fs';
import path from 'node:path';
import { REPO_ROOT, parseArgs } from '../lib/cli.mjs';

const args = parseArgs();
const OUT = path.join(REPO_ROOT, 'corpus/90-verdicts/wave1/artifacts/T4-r2');
const load = (p) => { try { return JSON.parse(fs.readFileSync(p, 'utf8')); } catch { return null; } };
const live = load(path.join(OUT, 'measure-live-1920x1080.json'));
const narrow = load(path.join(OUT, 'measure-live-844x390.json'));
const ctl = load(String(args.control || path.join(OUT, 'measure-baseline-1920x1080.json')));

if (!live) { console.error('no live measurement at ' + path.join(OUT, 'measure-live-1920x1080.json')); process.exit(2); }

const pict = (s) => (s && s.pictorial_measured ? s.pictorial_measured.in_panel
  : (s && s.pictorial_declared ? s.pictorial_declared.in_panel : null));
const fill = (s) => (s && s.panel_fill ? s.panel_fill.fill : null);
const n = (v) => (v === null || v === undefined ? '—' : String(v));

const screens = [...new Set([...Object.keys(live.screens || {}), ...(ctl ? Object.keys(ctl.screens || {}) : [])])];
const L = [];
L.push('# T4 round 2 — the measurements, both arms');
L.push('');
L.push('Generated by `tools/ui/t4-r2-evidence.mjs` from the JSONs beside this file. Every figure here');
L.push('is read off a measurement file at generation time; none is typed.');
L.push('');
L.push('| arm | commit | viewport | instrument |');
L.push('|---|---|---|---|');
L.push(`| **live** (this round) | \`${live.commit}\` | ${live.viewport.join('×')} | \`tools/ui/t4-r2-measure.mjs\` |`);
if (ctl) L.push(`| **control** (delete-the-fix) | \`${ctl.commit}\` | ${ctl.viewport.join('×')} | the same file, copied into the worktree |`);
else L.push('| **control** | **NOT TAKEN** | — | see §"what is missing" |');
if (narrow) L.push(`| **live, narrow** | \`${narrow.commit}\` | ${narrow.viewport.join('×')} | same |`);
L.push('');
L.push('**The control is a real `git worktree` at a pinned sha, not a hard-link copy of the live tree**');
L.push('(`git worktree add --detach <dir> ed140939636718afa984ee95732356207edee59a`), which is the commit');
L.push("the round-1 verdict states it judged at. `HEAD` was not used as the baseline: a sibling's");
L.push('whole-tree bank can carry an uncommitted edit into it, and this tree took four such banks');
L.push('during this piece.');
L.push('');

L.push('## The two numbers the round is about');
L.push('');
L.push('`D1` is RI-UIX09 method 2 — pictorial elements (`item_icon | doll | glyph_object`) inside the');
L.push("panel's own rect. `D2` is method 4 — the fraction of that rect's pixels at ΔE00 > 6 from the");
L.push("rect's own modal colour.");
L.push('');
L.push('| screen | D1 control | D1 live | D2 control | D2 live |');
L.push('|---|---|---|---|---|');
for (const s of screens) {
  const a = ctl ? ctl.screens[s] : null, b = live.screens[s];
  if (b && b.failed) { L.push(`| ${s} | ${n(pict(a))} | **step failed: ${b.failed}** | ${n(fill(a))} | — |`); continue; }
  L.push(`| ${s} | ${n(pict(a))} | ${n(pict(b))} | ${n(fill(a))} | ${n(fill(b))} |`);
}
L.push('');
L.push('**Both arms were measured with the same file.** The control publishes no `panel_rect`,');
L.push('no `pictorial` block and no `hud.world` — those are this round\'s additions — so the tool');
L.push('derives the panel rect and counts the pictorial kinds itself. That is RI-UIX09 method 4\'s own');
L.push('definition ("the largest `kind: \'panel\'` element"), and it is why the control column has');
L.push('numbers in it rather than blanks.');
L.push('');

L.push('## Every frame was screened before it was measured');
L.push('');
L.push('A sibling established on 2026-08-15 that the capture path can return a near-uniform buffer and');
L.push('report success — `shadow_levels=1`, `local_contrast_med=0` — and that a **+223%** result nearly');
L.push('got published off one. A degenerate frame makes an empty panel and a full one measure the same,');
L.push('which is exactly the property this round is measuring, so no fill figure is produced from a');
L.push('frame that fails the screen. `node tools/ui/t4-r2-measure.mjs --self-test` proves the screen can');
L.push('go red and is not inert-red — it caught a real defect in its own first version, which rejected a');
L.push('deliberately patterned control image.');
L.push('');
L.push('| screen | arm | levels | local_contrast_p95 | p10 → p90 | accepted |');
L.push('|---|---|---|---|---|---|');
for (const s of screens) {
  for (const [tag, j] of [['control', ctl], ['live', live]]) {
    const v = j && j.screens[s] && j.screens[s].frame_sanity;
    if (!v) continue;
    L.push(`| ${s} | ${tag} | ${v.levels} | ${v.local_contrast_p95 === undefined ? '—' : v.local_contrast_p95} | ${v.p10} → ${v.p90} | ${v.ok ? 'yes' : '**NO**'} |`);
  }
}
L.push('');

L.push('## RI-UIX07 — the world set');
L.push('');
const wl = (live.screens.world || {}).hud_world;
const wc = ctl && ctl.screens.world ? ctl.screens.world.hud_world : null;
if (wl) {
  L.push('| # | element | built | drawn on this frame | condition |');
  L.push('|---|---|---|---|---|');
  for (const [k, v] of Object.entries(wl.set)) {
    L.push(`| ${k.split('_')[0]} | \`${k.split('_').slice(1).join('_')}\` | ${v.built ? 'yes' : 'no'} | ${v.drawn ? 'yes' : 'no'}${v.expected === false ? ' *(condition not met)*' : ''} | ${v.conditional} |`);
  }
  L.push('');
  L.push('**V6 / §D1 — the rect that failed round 1.** The bearing dial was at `[1782, 84, 96, 96]`:');
  L.push('`y + h = 180` against `H/2 = 540`, wholly in the top half. Now:');
  L.push('');
  L.push('| id | kind | rect | `y + h > H/2` |');
  L.push('|---|---|---|---|');
  for (const e of wl.elements) L.push(`| \`${e.id}\` | ${e.kind} | \`[${e.rect.join(', ')}]\` | ${e.in_bottom_half} |`);
  L.push('');
  L.push(`All in the bottom half: **${wl.all_in_bottom_half}**. §D4 overlaps with any RI-UIX01 element: **${JSON.stringify(wl.overlaps)}** (derived from the drawn rects, not asserted).`);
  L.push(`World-set persistent coverage (§C C3, budget ≤ 1.5%): **${wl.coverage_pct}%**.`);
  if (!wc) L.push('');
  if (!wc) L.push('The control arm reports **no `hud.world` block at all** — the field did not exist at the baseline commit, which is the same thing as `ui.hud.world` scoring 1 of 6 with nothing to read it from.');
} else {
  L.push('**Not measured on this run** — the world screen produced no `hud.world` block.');
}
L.push('');

L.push('## The container header');
L.push('');
if (live.container_name_guard) {
  L.push('| value passed to `openContainer` | why | headers rendered | printed `undefined` |');
  L.push('|---|---|---|---|');
  for (const c of live.container_name_guard) {
    L.push(`| \`${JSON.stringify(c.passed)}\` | ${c.why} | ${c.headers.map((t) => '`' + t + '`').join(', ')} | ${c.any_undefined ? '**YES**' : 'no'} |`);
  }
  if (ctl && ctl.container_name_guard) {
    L.push('');
    L.push('The same five values on the **control** arm:');
    L.push('');
    L.push('| value | headers rendered | printed `undefined` |');
    L.push('|---|---|---|');
    for (const c of ctl.container_name_guard) {
      L.push(`| \`${JSON.stringify(c.passed)}\` | ${c.headers.map((t) => '`' + t + '`').join(', ')} | ${c.any_undefined ? '**YES — the old number came back**' : 'no'} |`);
    }
  }
} else {
  L.push('**Not measured on this run.**');
}
L.push('');

L.push('## Reference-item ids in player-facing text');
L.push('');
const riLive = Object.entries(live.screens).filter(([, v]) => (v.ri_citations || []).length);
const riCtl = ctl ? Object.entries(ctl.screens).filter(([, v]) => (v.ri_citations || []).length) : [];
L.push(`Live: **${riLive.length ? JSON.stringify(riLive.map(([k, v]) => [k, v.ri_citations])) : 'none on any screen'}**.`);
if (ctl) L.push(`Control: **${riCtl.length ? JSON.stringify(riCtl.map(([k, v]) => [k, v.ri_citations])) : 'none found on the screens this run reached'}**.`);
L.push('');

L.push('## What is missing, stated first rather than last');
L.push('');
const missing = [];
if (!ctl) missing.push('**The control arm did not complete.** Every "the old number comes back" claim in this file is therefore unmade, not made-and-passed.');
if (!narrow) missing.push('**The narrow-viewport pass did not complete.** The 844×390 landscape-phone captures are not in this evidence set.');
for (const [k, v] of Object.entries(live.screens)) if (v.failed) missing.push(`**\`${k}\` failed on the live arm**: ${v.failed}`);
if (ctl) for (const [k, v] of Object.entries(ctl.screens)) if (v.failed) missing.push(`**\`${k}\` failed on the control arm**: ${v.failed}`);
missing.push('**RI-UIX07 §G (V11) and RI-UIX09 DN7 are judge gates and were not run.** Rule 0 forbids spawning a session and rule 25 forbids judging a pack I built. They are the round-2 critic\'s.');
missing.push('**`D1` observed (method 3, the pixel half) is reported per screen in the JSON** under `d1_observed`; it is the half the item says will be dropped for being slow, so it is here.');
for (const m of missing) L.push('- ' + m);
L.push('');

const invLive = live.screens.inventory;
if (invLive && invLive.d1_observed) {
  L.push('## D1 observed — the pixel half');
  L.push('');
  L.push(`Inventory, live: **${invLive.d1_observed.rows_with_3_plus_hues_in_leading_48px} of ${invLive.d1_observed.rows}** item rows carry a region of ≥ 3 distinct hues in their leading 48 px; the worst row has ${invLive.d1_observed.min_hues}.`);
  const invCtl = ctl && ctl.screens.inventory;
  if (invCtl && invCtl.d1_observed) {
    L.push(`Inventory, control: **${invCtl.d1_observed.rows_with_3_plus_hues_in_leading_48px} of ${invCtl.d1_observed.rows}**; worst row ${invCtl.d1_observed.min_hues}.`);
  }
  L.push('');
  L.push('RI-UIX09 method 3 asks for both halves precisely because they can disagree: "a build that draws');
  L.push('icons straight to canvas without registering elements passes 3 and fails 2; a build that registers');
  L.push('icon elements and draws nothing fails 3 and passes 2."');
  L.push('');
}

fs.writeFileSync(path.join(OUT, 'EVIDENCE.md'), L.join('\n') + '\n');
console.log('wrote ' + path.join(OUT, 'EVIDENCE.md') + ` (${L.length} lines, control ${ctl ? 'present' : 'ABSENT'}, narrow ${narrow ? 'present' : 'ABSENT'})`);
