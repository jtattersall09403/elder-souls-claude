/**
 * emit-docs.mjs — W1-30K. Write ART.md and FIDELITY.md from board.json.
 *
 * The prose halves are GENERATED, not typed, and that is deliberate: the failure mode this child
 * exists to prevent is a look target that lives in prose and drifts from its own numbers. Edit the
 * commentary in this file; never edit ART.md or FIDELITY.md by hand.
 *
 * The two halves are disjoint by construction — each is built from rows of exactly one side, and
 * this file never puts a plate path from one side into the other's document. validate-board.mjs C2
 * and C3 check the result rather than trusting it.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(join(HERE, '..', '..'));
const B = JSON.parse(readFileSync(join(HERE, 'board.json'), 'utf8'));
const rows = B.rows;
const byId = new Map(rows.map((r) => [r.id, r]));
const fmt = (v) => (v === null || v === undefined ? '—' : String(v));
const rng = (r) => (r.status !== 'set' ? '**unset**'
  : r.target.hi === null ? `≥ ${fmt(r.target.lo)}` : `${fmt(r.target.lo)} … ${fmt(r.target.hi)}`);
const anchor = (r) => (r.status === 'set' ? fmt(r.target.anchor_p50) : '—');
const consumers = (r) => (r.consumers.length ? r.consumers.join(', ') : '*advisory*');
const nOf = (r) => (r.source ? r.source.statistic_n : 0);

// ---------------------------------------------------------------------------------------------
function crossTable(ids) {
  const out = ['| row | what is measured | range | anchor (p50) | n | consumed by |',
    '|---|---|---|---|---|---|'];
  for (const id of ids) {
    const r = byId.get(id); if (!r) continue;
    out.push(`| \`${r.id}\` | ${r.statistic} (${r.unit || '—'}) | ${rng(r)} | ${anchor(r)} | ${nOf(r)} | ${consumers(r)} |`);
  }
  return out.join('\n');
}

function scopeTable(scope, axes) {
  const subjects = [...new Set(rows.filter((r) => r.scope === scope).map((r) => r.subject))];
  const head = ['| ' + scope + ' | ' + axes.map((a) => a.label).join(' | ') + ' |',
    '|' + '---|'.repeat(axes.length + 1)];
  const body = subjects.map((s) => {
    const cells = axes.map((a) => {
      const r = rows.find((x) => x.scope === scope && x.subject === s && x.axis === a.axis);
      if (!r) return '—';
      return r.status === 'set' ? `${rng(r)}` : `**unset** (n=${r.source.population_n})`;
    });
    return `| \`${s}\` | ${cells.join(' | ')} |`;
  });
  return head.concat(body).join('\n');
}

function gapsTable(side) {
  const out = ['| row | why it is unset | what would fill it |', '|---|---|---|'];
  for (const r of rows.filter((x) => x.side === side && x.status === 'unset')) {
    out.push(`| \`${r.id}\` | ${(r.unset_reason || '').replace(/\|/g, '\\|')} | ${(r.would_fill || '—').replace(/\|/g, '\\|')} |`);
  }
  return out.join('\n');
}

const platesOf = (ids) => {
  const s = new Set();
  for (const id of ids) { const r = byId.get(id); if (r) for (const p of r.source.plates) s.add(p); }
  return [...s].sort();
};

